package main

// R.java escrito a partir de nuestra propia tabla de recursos (paso 3.4). Es el texto que hoy escribe
// aapt2 con `link --java`, y sale idéntico byte a byte: la prueba lo compara contra el fichero que
// dejó el SDK sobre el proyecto del studio (493 bytes, docs/evidencia.md 31).
//
// Lo medido, no supuesto:
//   - el id de recurso es el número de paquete desplazado 24, el id de tipo en los bits 16..23 y el
//     INDICE de la entrada dentro del tipo abajo (medido con dos entradas por tipo: id_bare
//     0x7f040000 y pulsar 0x7f040001, AppTheme 0x7f070000 y StyBare 0x7f070001).
//   - las clases anidadas van en el orden de los tipos, que es alfabético por nombre de tipo, y las
//     entradas en el orden en que van en el bloque, que también es alfabético por nombre de recurso.
//   - el nombre se desfigura para que sea identificador de Java: "con-guion.y.punto" sale
//     "con_guion_y_punto" — todo carácter fuera de letras, dígitos, guion bajo y dólar pasa a guion
//     bajo, medido con guion y punto.
//   - la cabecera son siete líneas de comentario, línea en blanco, `package`, línea en blanco y
//     `public final class R {`; dos espacios de sangrado por nivel y NINGÚN espacio alrededor del `=`;
//     el fichero termina en la llave de cierre, sin salto de línea.

import (
	"fmt"
	"strings"
)

const cabeceraR = `/* AUTO-GENERATED FILE. DO NOT MODIFY.
 *
 * This class was automatically generated by the
 * aapt tool from the resource data it found. It
 * should not be modified by hand.
 */

`

// rDeTabla da el texto completo de R.java para la tabla que se va a escribir. Rechaza lo que no está
// medido: un tipo cuyas entradas no van ordenadas por nombre (aapt2 las ordena, y el id depende de su
// lugar) y dos recursos que al desfigurar el nombre chocan en el mismo identificador.
func rDeTabla(t tablaEscribir) (string, error) {
	sb := strings.Builder{}
	sb.WriteString(cabeceraR)
	sb.WriteString("package " + t.nombrePaquete + ";\n\n")
	sb.WriteString("public final class R {\n")
	for _, ti := range t.tipos {
		if int(ti.id) > len(t.nombresTipo) {
			return "", fmt.Errorf("el tipo %d no tiene nombre en la tabla", ti.id)
		}
		nombre := t.nombresTipo[int(ti.id)-1]
		sb.WriteString("  public static final class " + nombre + " {\n")
		previa := ""
		usados := map[string]string{}
		for j, e := range ti.entradas {
			if e.clave < 0 || e.clave >= len(t.claves) {
				return "", fmt.Errorf("la entrada %d del tipo %s nombra la clave %d y hay %d", j, nombre, e.clave, len(t.claves))
			}
			clave := t.claves[e.clave]
			if j > 0 && clave < previa {
				return "", fmt.Errorf("las entradas de %s no van ordenadas por nombre: %q después de %q", nombre, clave, previa)
			}
			previa = clave
			identificador := identificadorJava(clave)
			if otra, ok := usados[identificador]; ok {
				return "", fmt.Errorf("%s y %s darían el mismo identificador %s", otra, clave, identificador)
			}
			usados[identificador] = clave
			id := t.idPaquete<<24 | uint32(ti.id)<<16 | uint32(j)
			fmt.Fprintf(&sb, "    public static final int %s=%#08x;\n", identificador, id)
		}
		sb.WriteString("  }\n")
	}
	sb.WriteString("}")
	return sb.String(), nil
}

// identificadorJava: letras, dígitos, guion bajo y dólar se quedan; lo demás pasa a guion bajo. Medido
// con "con-guion.y.punto" -> "con_guion_y_punto".
func identificadorJava(s string) string {
	out := make([]byte, 0, len(s))
	for i := 0; i < len(s); i++ {
		c := s[i]
		if c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c >= '0' && c <= '9' || c == '_' || c == '$' {
			out = append(out, c)
			continue
		}
		out = append(out, '_')
	}
	return string(out)
}
