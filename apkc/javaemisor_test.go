// jarDelSDK: el emisor resuelve los nombres contra el android.jar, así que sin jar no hay prueba. Se busca
// en la ruta del teléfono (el SDK está en ~/Android, dicho en AGENTS.md) y en la variable que el enlazador
// ya acepta, y si no aparece la prueba se salva en vez de fallar: en el hospedador de navegador no hay SDK.
func jarDelSDK(t *testing.T) string {
	t.Helper()
	rutas := []string{os.Getenv("APKC_ANDROID_JAR"), homeDir() + "/Android/platforms/android-34/android.jar"}
	for _, r := range rutas {
		if r == "" {
			continue
		}
		if _, err := os.Stat(r); err == nil {
			return r
		}
	}
	var vistas []string
	for _, r := range rutas {
		vistas = append(vistas, r)
	}
	t.Skipf("sin android.jar a mano (%s): el emisor resuelve los nombres contra el SDK", strings.Join(vistas, ", "))
	return ""
}

func homeDir() string {
	if h := os.Getenv("HOME"); h != "" {
		return h
	}
	return "/data/data/com.termux/files/home"
}

func compilarPlantilla(t *testing.T) []claseEmitida {
	t.Helper()
	salida, err := compilarProyectoJava([]fuenteJava{
		{nombre: "src/com/hola/j1g/MainActivity.java", contenido: fuenteMainActivityJ1g},
		{nombre: "src/com/hola/j1g/R.java", contenido: fuenteRJ1g},
	}, jarDelSDK(t))
	if err != nil {
		t.Fatalf("el emisor rechazó la plantilla: %v", err)
	}
	if len(salida) != 4 {
		t.Fatalf("salieron %d clases (%s), y javac deja cuatro", len(salida), nombresDe(salida))
	}
	return salida
}

func nombresDe(cs []claseEmitida) string {
	var v []string
	for _, c := range cs {
		v = append(v, c.interno)
	}
	return strings.Join(v, ", ")
}

func porInterno(cs []claseEmitida, interno string) *claseEmitida {
	for i := range cs {
		if cs[i].interno == interno {
			return &cs[i]
		}
	}
	return nil
}

func leer(t *testing.T, c *claseEmitida) classFull {
	t.Helper()
	cf, err := readClassFull(c.datos)
	if err != nil {
		t.Fatalf("nuestro propio lector rechaza lo que escribimos para %s: %v", c.interno, err)
	}
	return cf
}

// TestEmisorPlantillaContraJavap comprueba, contra los números del §40, que el ClassFile dice lo mismo.
func TestEmisorPlantillaContraJavap(t *testing.T) {
	salida := compilarPlantilla(t)

	main := porInterno(salida, "com/hola/j1g/MainActivity")
	if main == nil {
		t.Fatalf("no salió MainActivity: %s", nombresDe(salida))
	}
	cf := leer(t, main)
	if cf.Major != versionDeClassEmitida {
		t.Errorf("major version %d, se emite %d", cf.Major, versionDeClassEmitida)
	}
	if cf.Access != accPublic|accSuper {
		t.Errorf("access 0x%04x, javap dice 0x0021 (ACC_PUBLIC, ACC_SUPER)", cf.Access)
	}
	if cf.Name != "Lcom/hola/j1g/MainActivity;" {
		t.Errorf("nombre %q", cf.Name)
	}
	if cf.Super != "Landroid/app/Activity;" {
		t.Errorf("super %q, medido android/app/Activity (el lector de este fork guarda la forma descriptor)", cf.Super)
	}
	if cf.SourceFile != "MainActivity.java" {
		t.Errorf("SourceFile %q, medido MainActivity.java (el nombre, no la ruta)", cf.SourceFile)
	}
	if len(cf.Fields) != 0 {
		t.Errorf("%d campos, medidos cero", len(cf.Fields))
	}
	if len(cf.Methods) != 2 {
		t.Fatalf("%d métodos: %v", len(cf.Methods), cf.Methods)
	}

	init, onCreate := cf.Methods[0], cf.Methods[1]
	if init.Name != "<init>" || init.Desc != "()V" || init.Access != accPublic {
		t.Errorf("el <init> sintetizado sale %s %s 0x%04x, medido public <init>()V 0x0001", init.Name, init.Desc, init.Access)
	}
	// aload_0, invokespecial <android/app/Activity.<init>:()V>, return
	wantInit := []byte{0x2a, 0xb7, 0xee, 0xee, 0xb1}
	if !mismaForma(init.Code, wantInit) {
		t.Errorf("el <init> mide % x, esperado % x", init.Code, wantInit)
	}
	if got := lineasDe(init.Lines); got != "11:0" {
		t.Errorf("LineNumberTable del <init> %s, medida line 11: 0 (la línea de la declaración de clase)", got)
	}
	if init.MaxStack != 1 || init.LocalCount != 1 {
		t.Errorf("<init> stack=%d locals=%d, medidos stack=1 locals=1", init.MaxStack, init.LocalCount)
	}

	if onCreate.Name != "onCreate" || onCreate.Desc != "(Landroid/os/Bundle;)V" || onCreate.Access != accPublic {
		t.Errorf("onCreate sale %s %s 0x%04x", onCreate.Name, onCreate.Desc, onCreate.Access)
	}
	// aload_0, aload_1, invokespecial <Activity.onCreate>, aload_0, ldc <int>, invokevirtual <setContentView>,
	// return; 0xee es "cualquier byte" en los operandos que son indices del pool
	wantCreate := []byte{0x2a, 0x2b, 0xb7, 0xee, 0xee, 0x2a, 0x12, 0xee, 0xb6, 0xee, 0xee, 0xb1}
	if !mismaForma(onCreate.Code, wantCreate) {
		t.Errorf("onCreate mide % x, esperado % x", onCreate.Code, wantCreate)
	}
	if got := lineasDe(onCreate.Lines); got != "14:0,15:5,16:11" {
		t.Errorf("LineNumberTable de onCreate %s, medida 14:0, 15:5, 16:11", got)
	}
	if onCreate.MaxStack != 2 || onCreate.LocalCount != 2 {
		t.Errorf("onCreate stack=%d locals=%d, medidos stack=2 locals=2", onCreate.MaxStack, onCreate.LocalCount)
	}

	// las tres referencias del pool, con el dueño que javac escribe: el <init> y el super contra Activity,
	// setContentView contra la clase actual (parrafo 40)
	refs := refsDeMetodo(t, cf.p)
	esperadas := [][3]string{
		{"android/app/Activity", "<init>", "()V"},
		{"android/app/Activity", "onCreate", "(Landroid/os/Bundle;)V"},
		{"com/hola/j1g/MainActivity", "setContentView", "(I)V"},
	}
	for _, e := range esperadas {
		if !contieneRef(refs, e) {
			t.Errorf("falta la referencia %v en el pool; salieron %v", e, refs)
		}
	}

	// el valor doblado de R.layout.main tiene que ser el Integer del pool, no un getstatic
	if !contieneEntero(cf.p, 0x7f010000) {
		t.Errorf("el pool de MainActivity no lleva el Integer 0x7f010000: la constante no se dobló")
	}

	// InnerClasses: una sola fila, la anidada que el código menciona, con los flags que javap imprimió
	if len(cf.Inners) != 1 {
		t.Fatalf("MainActivity trae %d filas de InnerClasses, medida una", len(cf.Inners))
	}
	in := cf.Inners[0]
	if in.inner != "Lcom/hola/j1g/R$layout;" || in.outer != "Lcom/hola/j1g/R;" || in.name != "layout" {
		t.Errorf("fila InnerClasses %v, medida layout=class com/hola/j1g/R$layout of com/hola/j1g/R", in)
	}
	if in.access != accPublic|accStatic|accFinal {
		t.Errorf("flags de la anidada 0x%04x, medidos public static final (0x0019)", in.access)
	}

	// la R y sus anidadas
	r := porInterno(salida, "com/hola/j1g/R")
	if r == nil {
		t.Fatalf("no salió R: %s", nombresDe(salida))
	}
	cfR := leer(t, r)
	if cfR.Access != accPublic|accFinal|accSuper {
		t.Errorf("R access 0x%04x, javap dice 0x0031", cfR.Access)
	}
	if len(cfR.Methods) != 1 || cfR.Methods[0].Name != "<init>" {
		t.Errorf("R trae %d métodos, medido uno: el <init> sintetizado", len(cfR.Methods))
	}
	if got := lineasDe(cfR.Methods[0].Lines); got != "10:0" {
		t.Errorf("LineNumberTable del <init> de R %s, medida line 10: 0", got)
	}
	if len(cfR.Inners) != 2 {
		t.Errorf("R trae %d filas de InnerClasses, medidas dos (layout y style)", len(cfR.Inners))
	}

	lay := porInterno(salida, "com/hola/j1g/R$layout")
	cfL := leer(t, lay)
	if cfL.Access != accPublic|accFinal|accSuper {
		t.Errorf("R$layout access 0x%04x, medido 0x0031: una anidada no lleva ACC_STATIC en su propio fichero", cfL.Access)
	}
	if len(cfL.Fields) != 1 {
		t.Fatalf("R$layout trae %d campos, medido uno", len(cfL.Fields))
	}
	f := cfL.Fields[0]
	if f.Name != "main" || f.Desc != "I" || f.Access != accPublic|accStatic|accFinal {
		t.Errorf("campo %s %s 0x%04x, medido public static final int main (0x0019)", f.Name, f.Desc, f.Access)
	}
	if !f.HasConst || f.ConstTag != 3 || f.ConstInt != 0x7f010000 {
		t.Errorf("ConstantValue del campo: hasConst=%v tag=%d valor=%#x, medido int 0x7f010000", f.HasConst, f.ConstTag, f.ConstInt)
	}
	if len(cfL.Methods) != 1 || cfL.Methods[0].Name != "<init>" {
		t.Errorf("R$layout trae %d métodos, medido uno", len(cfL.Methods))
	}
	if got := lineasDe(cfL.Methods[0].Lines); got != "11:0" {
		t.Errorf("LineNumberTable del <init> de R$layout %s, medida line 11: 0", got)
	}
	if len(cfL.Inners) != 1 || cfL.Inners[0].inner != "Lcom/hola/j1g/R$layout;" {
		t.Errorf("R$layout debe llevar su propia fila en InnerClasses, salieron %v", cfL.Inners)
	}
}

// TestEmisorDexaLoQueDexaJavac es el oráculo de verdad: el dex que sale de nuestras clases tiene que ser el
// mismo byte a byte que el dex que sale de las clases que javac dejó en disco para el mismo par de fuentes.
// Aquí el `mismo` es exacto: no hay debug_info, no hay anotaciones y los índices son los que derivan del
// mismo código.
func TestEmisorDexaLoQueDexaJavac(t *testing.T) {
	salida := compilarPlantilla(t)
	var nuestras []classFull
	for i := range salida {
		nuestras = append(nuestras, leer(t, &salida[i]))
	}
	dexNuestro, err := dexDeClases(nuestras)
	if err != nil {
		t.Fatalf("el dexer rechaza nuestras clases: %v", err)
	}

	var deJavac []classFull
	for _, b64 := range []string{javacMainActivity, javacR, javacRLayout, javacRStyle} {
		d, err := base64.StdEncoding.DecodeString(b64)
		if err != nil {
			t.Fatalf("el fixture no es base64: %v", err)
		}
		cf, err := readClassFull(d)
		if err != nil {
			t.Fatalf("el fixture de javac no se lee: %v", err)
		}
		deJavac = append(deJavac, cf)
	}
	dexJavac, err := dexDeClases(deJavac)
	if err != nil {
		t.Fatalf("el dexer rechaza las clases de javac: %v", err)
	}

	if len(dexNuestro) != len(dexJavac) {
		t.Fatalf("el dex de nuestras clases mide %d bytes y el de las de javac %d", len(dexNuestro), len(dexJavac))
	}
	diferencias := 0
	var tramos []int
	ultimo := -2
	for i := range dexNuestro {
		if dexNuestro[i] != dexJavac[i] {
			diferencias++
			if i != ultimo+1 {
				tramos = append(tramos, i)
			}
			ultimo = i
		}
	}
	if diferencias > 0 {
		t.Errorf("%d bytes distintos de %d, tramos que empiezan en %v (8..27 son la firma, que cambia con el contenido)", diferencias, len(dexNuestro), tramos)
		for _, i := range tramos {
			if i > 27 {
				t.Logf("byte %d: nuestro %#02x, de javac %#02x", i, dexNuestro[i], dexJavac[i])
			}
		}
	}
	if d, err := readDex(dexNuestro); err != nil {
		t.Errorf("el dex que escribimos no se relee: %v", err)
	} else if len(d.classes) != 4 {
		t.Errorf("%d class_defs, medidas cuatro", len(d.classes))
	}
}

// TestEmisorRechazaLoQueNoEmitio comprueba que el portero nombra: lo que no está medido no sale como un
// .class raro, sale como un error con el nombre de la construcción.
func TestEmisorRechazaLoQueNoEmitio(t *testing.T) {
	jar := jarDelSDK(t)
	casos := []struct {
		nombre string
		fuente string
		espera string
	}{
		{"una clase anonima", `package p;
import android.app.*;
public class MainActivity extends Activity {
    void f() { Object o = new Object() { }; }
}
`, "anonima"},
		{"un if", `package p;
public class C {
    void f() { if (true) return; }
}
`, "if"},
		{"un long", `package p;
public class C {
    void f() { long x = 1L; }
}
`, "long"},
		{"una anotacion que no es Override", `package p;
public class C {
    @Deprecated
    void f() { }
}
`, "anotacion"},
		{"un tipo que no existe", `package p;
public class C extends NoExiste {
}
`, "no se resuelve"},
	}
	for _, c := range casos {
		_, err := compilarJava(c.fuente, "C.java", jar)
		if err == nil {
			t.Errorf("%s: el emisor lo aceptó en silencio", c.nombre)
			continue
		}
		if !strings.Contains(err.Error(), c.espera) {
			t.Errorf("%s: el error no nombra la construcción (%q)", c.nombre, err)
		}
	}
}

