// mismaForma compara el código ignorando los operandos marcados con 0xee (los indices del pool, que en
// nuestro fichero salen en otro orden que en el de javac porque javac interna las entradas como quiere).
func mismaForma(got, want []byte) bool {
	if len(got) != len(want) {
		return false
	}
	for i := range got {
		if want[i] == 0xee {
			continue
		}
		if got[i] != want[i] {
			return false
		}
	}
	return true
}

func lineasDe(ls []classLine) string {
	var v []string
	for _, l := range ls {
		v = append(v, strconv.Itoa(l.line)+":"+strconv.Itoa(l.pc))
	}
	return strings.Join(v, ",")
}

// refsDeMetodo vuelve los Methodref y InterfaceMethodref del pool como (clase, nombre, descriptor).
func refsDeMetodo(t *testing.T, p *pool) [][3]string {
	t.Helper()
	var out [][3]string
	for i, tag := range p.tag {
		if tag != cpMethodref && tag != cpInterfaceMethodref {
			continue
		}
		body := p.body[i]
		if len(body) < 4 {
			t.Fatalf("un Methodref sin cuatro bytes de operandos en %d", i)
		}
		ci := int(binary.BigEndian.Uint16(body[0:2]))
		nt := int(binary.BigEndian.Uint16(body[2:4]))
		nb := p.body[nt]
		ni := int(binary.BigEndian.Uint16(nb[0:2]))
		di := int(binary.BigEndian.Uint16(nb[2:4]))
		out = append(out, [3]string{p.utf[p.class[ci]], p.utf[ni], p.utf[di]})
	}
	return out
}

func contieneRef(refs [][3]string, e [3]string) bool {
	for _, r := range refs {
		if r == e {
			return true
		}
	}
	return false
}

// contieneEntero mira si el pool tiene un Integer con ese valor, que es la huella de la constante doblada.
func contieneEntero(p *pool, v int32) bool {
	for i, tag := range p.tag {
		if tag != cpInteger && tag != 3 {
			continue
		}
		if len(p.body[i]) >= 4 && int32(binary.BigEndian.Uint32(p.body[i][0:4])) == v {
			return true
		}
	}
	return false
}

